/** Price per year when paying annually. */
export function annualPrice(monthly: number): number {
  return monthly * ANNUAL_MONTHS_PAID;
}

/** "1.290" style, Greek thousands separator, no decimals. */
export function formatEuro(amount: number): string {
  return new Intl.NumberFormat("el-GR", { maximumFractionDigits: 0, useGrouping: true }).format(amount);
}
