// ── Filling in the company details ─────────────────────────────────────────

export type TextPart = { text: string } | { missing: CompanyKey } | { link: string; href: string };

/** Splits a text into plain parts and company details (missing ones marked). */
export function fillCompany(text: string, company: Record<CompanyKey, string | null> = VGS_COMPANY): TextPart[] {
  const parts: TextPart[] = [];
  const re = /\{(\w+)\}/g;
  let last = 0;
  for (let m = re.exec(text); m; m = re.exec(text)) {
    if (m.index > last) parts.push({ text: text.slice(last, m.index) });
    const key = m[1] as CompanyKey;
    if (!(key in company)) throw new Error(`Unknown company detail {${key}}`);
    const value = company[key];
    parts.push(value ? { text: value } : { missing: key });
    last = m.index + m[0].length;
  }
  if (last < text.length) parts.push({ text: text.slice(last) });
  // neighbouring plain parts merged
  return parts.reduce<TextPart[]>((acc, p) => {
    const prev = acc[acc.length - 1];
    if (prev && "text" in prev && "text" in p) prev.text += p.text;
    else acc.push({ ...p });
    return acc;
  }, []);
}

/** Company details still to be filled in (shown to the platform owner). */
export function missingCompanyDetails(company: Record<CompanyKey, string | null> = VGS_COMPANY): CompanyKey[] {
  return (Object.keys(company) as CompanyKey[]).filter((k) => !company[k]);
}

/** Splits further on [label](/path) links (only links inside this site). */
export function textParts(text: string, company: Record<CompanyKey, string | null> = VGS_COMPANY): TextPart[] {
  return fillCompany(text, company).flatMap((part) => {
    if (!("text" in part)) return [part];
    const out: TextPart[] = [];
    const re = /\[([^\]]+)\]\((\/[^)\s]*)\)/g;
    let last = 0;
    for (let m = re.exec(part.text); m; m = re.exec(part.text)) {
      if (m.index > last) out.push({ text: part.text.slice(last, m.index) });
      out.push({ link: m[1], href: m[2] });
      last = m.index + m[0].length;
    }
    if (last < part.text.length) out.push({ text: part.text.slice(last) });
    return out;
  });
}

/** Every text of a document, for checks. */
export function docTexts(doc: { intro?: string; sections: LegalSection[] }): string[] {
  return [doc.intro ?? "", ...doc.sections.flatMap((s) => [s.title, ...(s.paragraphs ?? []), ...(s.points ?? []), ...(s.after ?? [])])];
}

/** The text without link marks or gaps, e.g. for a page description. */
export function plainText(text: string): string {
  return textParts(text)
    .map((p) => ("text" in p ? p.text : "link" in p ? p.link : ""))
    .join("")
    .replace(/\s+/g, " ")
    .trim();
}
